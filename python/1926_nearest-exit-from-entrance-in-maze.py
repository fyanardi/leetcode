class Solution:
    def nearestExit(self, maze: list[list[str]], entrance: list[int]) -> int:
        m = len(maze)
        n = len(maze[0])

        start = (entrance[0], entrance[1])

        visited_lengths = {start: 0}

        from collections import deque
        nodes = deque()
        nodes.append(start)

        while len(nodes) > 0:
            node = nodes.popleft()

            row = node[0]
            col = node[1]

            for next in ((row, col - 1), (row, col + 1), (row - 1, col), (row + 1, col)):
                if next in visited_lengths:
                    continue

                if next[0] == -1 or next[0] == m or next[1] == -1 or next[1] == n:
                    continue

                if maze[next[0]][next[1]] == '+':
                    visited_lengths[next] = -1
                    continue

                visited_lengths[next] = visited_lengths[node] + 1

                if next[0] == 0 or next[1] == 0 or next[0] == m - 1 or next[1] == n - 1:
                    return visited_lengths[next]

                nodes.append(next)

        return -1


